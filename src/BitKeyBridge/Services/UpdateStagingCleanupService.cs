using System.Text.RegularExpressions;

namespace BitKeyBridge;

/// <summary>
/// Bounded cleanup of OLD updater *staging* folders only. Never traverses
/// outside ProgramData/BitKeyBridge/Updates, follows reparse points, deletes
/// an active helper/current version, or touches .bak, policies, audit and
/// recovery data. All deletion is optional when housekeeping is disabled.
/// </summary>
internal static class UpdateStagingCleanupService
{
    private const int MaximumDirectoriesPerRun = 128;

    private static readonly Regex VersionName = new(
        @"^v[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?$",
        RegexOptions.Compiled | RegexOptions.CultureInvariant |
        RegexOptions.IgnoreCase);

    private static readonly Regex TransientName = new(
        @"^(?:helper|rollback)-[0-9a-f]{32}$",
        RegexOptions.Compiled | RegexOptions.CultureInvariant |
        RegexOptions.IgnoreCase);

    internal static void Run(
        string updatesRoot, int retentionDays, bool dryRun,
        HousekeepingStatus report, string? currentVersion = null,
        DateTime? utcNow = null, bool useUpdateGates = true)
    {
        if (retentionDays <= 0 || !Directory.Exists(updatesRoot))
            return;

        // A download from the scheduled updater owns the async semaphore,
        // while actual replacement owns the update mutex. Never delete a
        // directory while either protected phase is underway.
        if (useUpdateGates)
        {
            try
            {
                using var scheduler = ScheduledUpdateGate.TryAcquire(
                    timeout: TimeSpan.Zero);
                if (scheduler is null)
                {
                    report.Warnings.Add(
                        "Updater staging cleanup skipped: a download is in progress.");
                    return;
                }
                using var apply = UpdateApplyGate.TryAcquire(
                    timeout: TimeSpan.Zero);
                if (apply is null)
                {
                    report.Warnings.Add(
                        "Updater staging cleanup skipped: an apply or rollback is active.");
                    return;
                }
                Prune(updatesRoot, retentionDays, dryRun, report,
                    currentVersion, utcNow, respectRollbackHold: true);
            }
            catch (Exception ex)
            {
                report.UpdateFolderErrors++;
                report.Errors.Add("Updater cleanup gate: " +
                    DiagnosticRedaction.Sanitize(ex.Message));
            }
            return;
        }

        // Used by isolated --self-test fixtures only, never by the
        // production service or its privileged update pathway.
        Prune(updatesRoot, retentionDays, dryRun, report,
            currentVersion, utcNow, respectRollbackHold: false);
    }

    private static void Prune(
        string updatesRoot, int retentionDays, bool dryRun,
        HousekeepingStatus report, string? currentVersion, DateTime? utcNow,
        bool respectRollbackHold)
    {
        var root = Path.GetFullPath(updatesRoot);
        var cutoff = (utcNow ?? DateTime.UtcNow).AddDays(
            -Math.Clamp(retentionDays, 1, 3650));
        if ((File.GetAttributes(root) & FileAttributes.ReparsePoint) != 0)
        {
            report.UpdateFolderErrors++;
            report.Errors.Add("Updater staging root is a reparse point; nothing deleted.");
            return;
        }

        var protectedVersion = "v" +
            (currentVersion ?? UpdateService.GetCurrentVersion().ToString());
        var processPath = Environment.ProcessPath;
        var activeExecutable = string.IsNullOrWhiteSpace(processPath)
            ? string.Empty : Path.GetFullPath(processPath);

        // Only top-level directories with names generated by OUR updater.
        // This intentionally ignores any other ProgramData directory,
        // files directly in Updates, and all persistent .bak/hold/history.
        foreach (var candidate in Directory.EnumerateDirectories(root)
                     .Take(MaximumDirectoriesPerRun + 1))
        {
            if (report.UpdateFoldersScanned >= MaximumDirectoriesPerRun)
            {
                report.Warnings.Add(
                    "Updater staging cleanup reached its per-run directory limit.");
                break;
            }

            var name = Path.GetFileName(candidate);
            if (!VersionName.IsMatch(name) && !TransientName.IsMatch(name))
                continue;

            report.UpdateFoldersScanned++;

            if (string.Equals(name, protectedVersion,
                    StringComparison.OrdinalIgnoreCase) ||
                (!string.IsNullOrEmpty(activeExecutable) &&
                 activeExecutable.StartsWith(
                     Path.GetFullPath(candidate) + Path.DirectorySeparatorChar,
                     StringComparison.OrdinalIgnoreCase)))
                continue;

            // A deliberate rollback hold is critical recovery state.
            // If its metadata is damaged, IsActiveForVersion fails closed.
            if (respectRollbackHold && VersionName.IsMatch(name) &&
                UpdateRollbackHoldService.IsActiveForVersion(name[1..]))
                continue;

            try
            {
                // Check the candidate itself before enumerating children.
                // A junction named v0.30.0 must never direct cleanup outside
                // the dedicated Updates root.
                if ((File.GetAttributes(candidate) &
                     FileAttributes.ReparsePoint) != 0)
                    throw new IOException(
                        "Updater staging directory is a reparse point; preserved.");

                var lastWrite = LastModifiedTreeUtcOrRejectReparse(candidate);
                if (lastWrite >= cutoff)
                    continue;

                report.UpdateFoldersCandidates++;
                if (dryRun)
                    continue;

                var bytes = DirectoryBytes(candidate);
                Directory.Delete(candidate, recursive: true);
                report.UpdateFoldersDeleted++;
                report.BytesFreed += bytes;
            }
            catch (Exception ex)
            {
                // If locked, busy, protected, or linked: retain the entire
                // tree. Do not retry with forced permissions or reboot moves.
                report.UpdateFolderErrors++;
                report.Errors.Add("Updater staging '" + name + "': " +
                    DiagnosticRedaction.Sanitize(ex.Message));
            }
        }
    }

    private static DateTime LastModifiedTreeUtcOrRejectReparse(string directory)
    {
        var latest = Directory.GetLastWriteTimeUtc(directory);
        var pending = new Stack<string>();
        pending.Push(directory);
        while (pending.Count > 0)
        {
            var next = pending.Pop();
            foreach (var entry in new DirectoryInfo(next).EnumerateFileSystemInfos())
            {
                if ((entry.Attributes & FileAttributes.ReparsePoint) != 0)
                    throw new IOException(
                        "Updater staging contains a reparse point; preserved.");
                if (entry.LastWriteTimeUtc > latest)
                    latest = entry.LastWriteTimeUtc;
                if ((entry.Attributes & FileAttributes.Directory) != 0)
                    pending.Push(entry.FullName);
            }
        }
        return latest;
    }

    private static long DirectoryBytes(string directory)
    {
        long total = 0;
        foreach (var file in Directory.EnumerateFiles(
                     directory, "*", SearchOption.AllDirectories))
            total = checked(total + new FileInfo(file).Length);
        return total;
    }

    internal static IEnumerable<string> RunOfflineTests(string scratchDirectory)
    {
        var errors = new List<string>();
        var root = Path.Combine(scratchDirectory, "updater-cleanup-fixture");
        Directory.CreateDirectory(root);
        var now = DateTime.UtcNow;
        void Seed(string name, int ageDays)
        {
            var path = Path.Combine(root, name);
            Directory.CreateDirectory(path);
            var file = Path.Combine(path, "fixture.bin");
            File.WriteAllText(file, "synthetic updater fixture");
            File.SetLastWriteTimeUtc(file, now.AddDays(-ageDays));
            Directory.SetLastWriteTimeUtc(path, now.AddDays(-ageDays));
        }

        try
        {
            var oldVersion = "v0.28.1";
            var current = "v0.32.0-rc.8";
            var oldHelper = "helper-" + Guid.NewGuid().ToString("N");
            var oldRollback = "rollback-" + Guid.NewGuid().ToString("N");
            var fresh = "v0.31.0";
            var unknown = "ProtectedAudit";
            Seed(oldVersion, 30);
            Seed(current, 30);
            Seed(oldHelper, 30);
            Seed(oldRollback, 30);
            Seed(fresh, 1);
            Seed(unknown, 30);

            var dry = new HousekeepingStatus();
            Run(root, 7, true, dry, current[1..], now, false);
            if (dry.UpdateFoldersCandidates != 3 ||
                dry.UpdateFoldersDeleted != 0)
                errors.Add("Updater dry run must report exactly three stale staging folders.");
            var actual = new HousekeepingStatus();
            Run(root, 7, false, actual, current[1..], now, false);
            if (actual.UpdateFoldersDeleted != 3 ||
                Directory.Exists(Path.Combine(root, oldVersion)) ||
                Directory.Exists(Path.Combine(root, oldHelper)) ||
                Directory.Exists(Path.Combine(root, oldRollback)))
                errors.Add("Updater cleanup failed to delete only its three stale fixtures.");
            if (!Directory.Exists(Path.Combine(root, current)) ||
                !Directory.Exists(Path.Combine(root, fresh)) ||
                !Directory.Exists(Path.Combine(root, unknown)))
                errors.Add("Updater cleanup deleted active, recent or unknown data.");

            var disabled = new HousekeepingStatus();
            Run(root, 0, false, disabled, current[1..], now, false);
            if (disabled.UpdateFoldersDeleted != 0)
                errors.Add("Updater cleanup ignored disabled retention.");
        }
        catch (Exception ex)
        {
            errors.Add("Updater staging cleanup: " +
                DiagnosticRedaction.Sanitize(ex.Message));
        }
        return errors;
    }
}
